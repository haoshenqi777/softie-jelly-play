// Offline only: measure the actual product mesh rather than assuming a sphere.
// Regenerate after changing its tessellation, bevel or erosion formula.
import { writeFileSync } from 'node:fs';
import { Vector3 } from 'three/webgpu';
import { RoundedBoxGeometry } from 'three/addons/geometries/RoundedBoxGeometry.js';
import { mergeVertices } from 'three/addons/utils/BufferGeometryUtils.js';
import { erodedCandyPoint } from '../lib/contact-intake.ts';
import { HARD_CUBE_BEVEL, BASE_CANDY_RADIUS } from '../lib/candy-physics.ts';
const raw = new RoundedBoxGeometry(0.17, 0.17, 0.17, 3, HARD_CUBE_BEVEL);
raw.deleteAttribute('uv');
const g = mergeVertices(raw, 0.0001);
g.scale(
  0.18 / BASE_CANDY_RADIUS,
  0.18 / BASE_CANDY_RADIUS,
  0.18 / BASE_CANDY_RADIUS,
);
const p = g.attributes.position,
  rest = p.array.slice(),
  index = g.index;
function volume() {
  const a = new Vector3(),
    b = new Vector3(),
    c = new Vector3();
  let v = 0;
  for (let i = 0; i < index.count; i += 3) {
    a.fromBufferAttribute(p, index.getX(i));
    b.fromBufferAttribute(p, index.getX(i + 1));
    c.fromBufferAttribute(p, index.getX(i + 2));
    v += a.dot(b.cross(c)) / 6;
  }
  return Math.abs(v);
}
const initial = volume(),
  profile = [];
for (let step = 0; step <= 64; step++) {
  for (let i = 0; i < p.count; i++) {
    const q = erodedCandyPoint(
      [rest[i * 3], rest[i * 3 + 1], rest[i * 3 + 2]],
      step / 64,
      (HARD_CUBE_BEVEL * 0.18) / BASE_CANDY_RADIUS,
    );
    p.setXYZ(i, ...q);
  }
  profile.push(Number((volume() / initial).toFixed(7)));
}
writeFileSync(
  new URL('../lib/hard-candy-volume.ts', import.meta.url),
  '// Generated by tools/calibrate-candy-volume.mjs from the actual product cube.\nexport const HARD_CUBE_VOLUMES = ' +
    JSON.stringify(profile) +
    ' as const;\n',
);
process.stdout.write(
  JSON.stringify({
    samples: profile.length,
    monotone: profile.every((v, i) => !i || v <= profile[i - 1]),
  }) + '\n',
);
